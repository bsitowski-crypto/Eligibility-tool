(function(){
  "use strict";
  let installed=false;

  function replaceBrandText(root){
    root=root||document.body;
    if(!root)return;
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT,{acceptNode(node){
      const p=node.parentElement;
      if(!p||/^(SCRIPT|STYLE|TEXTAREA)$/i.test(p.tagName))return NodeFilter.FILTER_REJECT;
      return /solvita/i.test(node.nodeValue||"")?NodeFilter.FILTER_ACCEPT:NodeFilter.FILTER_REJECT;
    }});
    const nodes=[];let n;while((n=walker.nextNode()))nodes.push(n);
    for(const node of nodes)node.nodeValue=node.nodeValue.replace(/Solvita/gi,"PDX");
    document.querySelectorAll('[title],[aria-label],input[placeholder]').forEach(el=>{
      for(const a of ["title","aria-label","placeholder"]){
        if(el.hasAttribute(a)&&/solvita/i.test(el.getAttribute(a)||""))el.setAttribute(a,(el.getAttribute(a)||"").replace(/Solvita/gi,"PDX"));
      }
    });
    if(/solvita/i.test(document.title))document.title=document.title.replace(/Solvita/gi,"PDX");
  }

  function removeNameFields(){
    const first=document.getElementById("firstName"),last=document.getElementById("lastName");
    if(!first&&!last)return;
    [first,last].forEach(el=>{if(!el)return;el.value="";el.disabled=true;el.autocomplete="off";const fg=el.closest(".fg");if(fg)fg.style.display="none";});
    const row=first?.closest(".row")||last?.closest(".row");
    if(row){const visible=[...row.children].some(x=>x.style.display!=="none");if(!visible)row.style.display="none";}
  }

  function apply(){removeNameFields();replaceBrandText(document.body);}

  function wrap(name,after){
    const fn=window[name];if(typeof fn!=="function"||fn.__pdxPrivacyWrapped)return;
    const w=function(){const r=fn.apply(this,arguments);try{after&&after.apply(this,arguments)}catch{};setTimeout(apply,0);return r};
    w.__pdxPrivacyWrapped=true;window[name]=w;
  }

  function install(){
    if(installed)return true;
    if(!document.getElementById("plannerView")||!document.getElementById("firstName"))return false;
    installed=true;

    // Anonymous display label for donor cards and archives.
    if(typeof window.dname==="function")window.dname=function(){return "PDX DONOR"};

    // Never load a stored donor name back into the form. Normal snapshot/save will
    // subsequently persist blanks without altering any other donor fields.
    wrap("loadDonor",function(){
      const first=document.getElementById("firstName"),last=document.getElementById("lastName");
      if(first)first.value="";if(last)last.value="";
    });

    ["renderBoard","renderArchive","renderHospitals","renderFunerals","renderCriteria","screenDonor","buildRecovery","validateRecovery","show","openDonor"].forEach(n=>wrap(n));

    document.addEventListener("click",()=>{setTimeout(apply,0);setTimeout(apply,120)},true);
    document.addEventListener("change",()=>setTimeout(apply,0),true);
    apply();
    // Low-frequency safety pass for content generated by print/modals or add-on scripts.
    setInterval(apply,4000);
    return true;
  }

  let tries=0;const timer=setInterval(()=>{tries++;if(install()||tries>60)clearInterval(timer)},200);
})();
